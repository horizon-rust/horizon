import contextlib
import io
import json
from pathlib import Path
import re
import tempfile
import unittest
from unittest import mock

from tools import generate_packet_ids as gen

REPORT = {
    "handshake": {
        "serverbound": {
            "minecraft:intention": {"protocol_id": 0},
        },
    },
    "play": {
        "clientbound": {
            "minecraft:keep_alive": {"protocol_id": 0},
            "minecraft:chat": {"protocol_id": 1},
        },
        "serverbound": {
            "minecraft:chat_command": {"protocol_id": 0},
        },
    },
}
INFO = {"protocol_version": 777, "name": "26.3"}


class RenderTests(unittest.TestCase):
    def test_renders_the_ids_of_every_state_and_direction(self):
        text = gen.render(REPORT, INFO)
        self.assertIn("pub mod handshake {", text)
        self.assertIn("pub const INTENTION: i32 = 0;", text)
        self.assertIn("pub const KEEP_ALIVE: i32 = 0;", text)
        self.assertIn("pub const CHAT: i32 = 1;", text)
        self.assertIn("pub const CHAT_COMMAND: i32 = 0;", text)

    def test_the_ids_follow_the_protocol_ids_not_the_order(self):
        text = gen.render(REPORT, INFO)
        clientbound = text.split("pub mod clientbound {")[1].split("pub mod serverbound {")[0]
        self.assertLess(clientbound.index("KEEP_ALIVE"), clientbound.index("pub const CHAT:"))

    def test_the_names_are_indexed_by_id(self):
        text = gen.render(REPORT, INFO)
        self.assertIn('pub const NAMES: &[&str] = &["keep_alive", "chat"];', text)

    def test_the_header_names_the_protocol(self):
        text = gen.render(REPORT, INFO)
        self.assertTrue(text.startswith("//! Packet ids per connection state and direction for protocol 777 (26.3)."))


class CheckTests(unittest.TestCase):
    """--check compares the committed file with the report instead of writing it."""

    def _run(self, report, out, check):
        with tempfile.TemporaryDirectory() as directory:
            report_path = Path(directory) / "packets.json"
            report_path.write_text(json.dumps(report))
            out_path = Path(directory) / "ids.rs"
            if out is not None:
                out_path.write_text(out)
            argv = ["generate_packet_ids.py", "--report", str(report_path), "--out", str(out_path)]
            if check:
                argv.append("--check")
            with mock.patch.object(gen.lab, "version_info", return_value=INFO), \
                 mock.patch.object(gen.sys, "argv", argv):
                return gen.main()

    def test_a_matching_file_passes(self):
        # The committed file is rustfmt-formatted, so --check formats the render too.
        text = gen.format_rust(gen.render(REPORT, INFO))
        self.assertEqual(self._run(REPORT, text, check=True), 0)

    def test_a_different_file_fails(self):
        self.assertEqual(self._run(REPORT, "//! stale\n", check=True), 1)

    def test_a_missing_file_fails(self):
        self.assertEqual(self._run(REPORT, None, check=True), 1)

    def test_without_check_the_file_is_written(self):
        text = gen.render(REPORT, INFO)
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(self._run(REPORT, text, check=False), 0)
        self.assertEqual(text, gen.render(REPORT, INFO))


class CommittedFileTests(unittest.TestCase):
    """The committed ids.rs and the pinned version agree."""

    def test_the_committed_file_names_the_pinned_protocol(self):
        text = gen.OUT.read_text()
        version = (gen.ROOT / "crates/horizon-core/src/version.rs").read_text()
        protocol = re.search(r"PROTOCOL_VERSION: i32 = (\d+);", version)[1]
        name = re.search(r'VANILLA_VERSION: &str = "([^"]+)";', version)[1]
        self.assertIn(f"protocol {protocol} ({name})", text.splitlines()[0])

    def test_the_committed_file_says_it_is_generated(self):
        self.assertIn("Generated by tools/generate_packet_ids.py", gen.OUT.read_text())


if __name__ == "__main__":
    unittest.main()
